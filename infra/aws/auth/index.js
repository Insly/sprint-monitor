'use strict';
/*
 * Lambda@Edge, viewer-request: Microsoft Entra ID sign-in in front of the MGA Sprint Board.
 *
 * Flow (OIDC authorization code + PKCE, confidential client):
 *   1. No valid session cookie on a page navigation -> 302 to Entra /authorize
 *      (state, nonce and PKCE verifier kept in a short-lived signed cookie).
 *   2. Entra -> /_auth/callback?code&state -> back-channel code redemption at the token endpoint,
 *      ID token claims checked (iss, aud, tid, nonce, exp) -> signed session cookie -> 302 back.
 *   3. Valid session cookie -> request passes through to S3 unchanged.
 * Who may sign in is decided in Entra ("Assignment required" on the enterprise app), not here.
 *
 * The ID token arrives directly from Entra's token endpoint over TLS, so per OIDC Core 3.1.3.7
 * TLS server validation stands in for the signature check: no JWKS fetch, no dependencies.
 * Only the AWS SDK (bundled in the Lambda Node.js runtime) is used.
 *
 * config.json is generated by OpenTofu (auth.tf) because Lambda@Edge has no env variables.
 * Secrets come from SSM Parameter Store (SecureString JSON: clientSecret, cookieKey).
 *
 * UNREVIEWED SKELETON: smoke-tested locally with stubs only; review + test before first use.
 */
const crypto = require('node:crypto');
const { SSMClient, GetParameterCommand } = require('@aws-sdk/client-ssm');
const config = require('./config.json');

const SESSION_COOKIE = '__Host-sm_session';
const FLOW_COOKIE = '__Host-sm_flow';
const CALLBACK_PATH = '/_auth/callback';
const LOGOUT_PATH = '/_auth/logout';
const HEALTH_PATH = '/_auth/health';
const FLOW_TTL_S = 600;
const SESSION_TTL_S = Math.round(Number(config.sessionHours || 12) * 3600);
const SECRET_CACHE_MS = 5 * 60 * 1000;
const TOKEN_TIMEOUT_MS = 3500; // viewer-request hard limit is 5 s
const AUTHORITY = `https://login.microsoftonline.com/${config.tenantId}`;
const ISSUER = `${AUTHORITY}/v2.0`;
const SCOPE = 'openid profile'; // profile: v2 ID tokens carry oid only with it

const ssm = new SSMClient({ region: config.ssmRegion || 'us-east-1' });
let secretCache = null;

const now = () => Math.floor(Date.now() / 1000);
const rand = (bytes = 24) => crypto.randomBytes(bytes).toString('base64url');

async function getSecrets() {
  if (secretCache && Date.now() - secretCache.at < SECRET_CACHE_MS) return secretCache.value;
  const out = await ssm.send(new GetParameterCommand({ Name: config.secretParameter, WithDecryption: true }));
  const raw = out.Parameter && out.Parameter.Value;
  const value = JSON.parse(raw || '{}');
  if (!value.clientSecret || !value.cookieKey || value.cookieKey.length < 32 || raw.includes('SET-OUT-OF-BAND')) {
    throw new Error('edge auth secrets are not configured');
  }
  secretCache = { value, at: Date.now() };
  return value;
}

// --- signed cookies (HMAC-SHA256, payload is not secret, only tamper-proof) ---

function sign(payload, key) {
  const body = Buffer.from(JSON.stringify(payload)).toString('base64url');
  const mac = crypto.createHmac('sha256', key).update(body).digest('base64url');
  return `${body}.${mac}`;
}

function verify(token, key) {
  if (typeof token !== 'string' || token.length > 2048) return null;
  const dot = token.indexOf('.');
  if (dot < 1) return null;
  const body = token.slice(0, dot);
  const mac = Buffer.from(token.slice(dot + 1));
  const expected = Buffer.from(crypto.createHmac('sha256', key).update(body).digest('base64url'));
  if (mac.length !== expected.length || !crypto.timingSafeEqual(mac, expected)) return null;
  try {
    const payload = JSON.parse(Buffer.from(body, 'base64url').toString('utf8'));
    return payload && typeof payload.exp === 'number' && payload.exp > now() ? payload : null;
  } catch {
    return null;
  }
}

// --- request helpers ---

function header(request, name) {
  const h = request.headers[name];
  return h && h[0] ? h[0].value : '';
}

function parseCookies(request) {
  const out = {};
  for (const h of request.headers.cookie || []) {
    for (const part of h.value.split(';')) {
      const i = part.indexOf('=');
      if (i > 0) out[part.slice(0, i).trim()] = part.slice(i + 1).trim();
    }
  }
  return out;
}

// Old browsers send no Sec-Fetch-Mode: treat as a navigation.
const isNavigation = (request) => {
  const mode = header(request, 'sec-fetch-mode');
  return !mode || mode === 'navigate';
};

const redirectUri = (host) => `https://${host}${CALLBACK_PATH}`;

function safeReturnTo(uri, querystring) {
  if (typeof uri !== 'string' || !uri.startsWith('/') || uri.startsWith('//') || uri.includes('\\') || uri.startsWith('/_auth/')) return '/';
  const full = querystring ? `${uri}?${querystring}` : uri;
  return full.length <= 512 ? full : '/';
}

// --- responses ---

const cookie = (name, value, maxAge) => `${name}=${value}; Path=/; Max-Age=${maxAge}; Secure; HttpOnly; SameSite=Lax`;
const clearCookie = (name) => cookie(name, '', 0);

const BASE_HEADERS = {
  'cache-control': [{ key: 'Cache-Control', value: 'no-store' }],
  'x-content-type-options': [{ key: 'X-Content-Type-Options', value: 'nosniff' }],
  'referrer-policy': [{ key: 'Referrer-Policy', value: 'no-referrer' }],
  'strict-transport-security': [{ key: 'Strict-Transport-Security', value: 'max-age=63072000' }],
  'content-security-policy': [{ key: 'Content-Security-Policy', value: "default-src 'none'; frame-ancestors 'none'" }],
};

function withCookies(headers, cookies) {
  if (cookies.length) headers['set-cookie'] = cookies.map((value) => ({ key: 'Set-Cookie', value }));
  return headers;
}

function redirect(location, cookies = []) {
  return {
    status: '302',
    statusDescription: 'Found',
    headers: withCookies({ ...BASE_HEADERS, location: [{ key: 'Location', value: location }] }, cookies),
  };
}

function page(status, statusDescription, html, cookies = []) {
  return {
    status,
    statusDescription,
    headers: withCookies({ ...BASE_HEADERS, 'content-type': [{ key: 'Content-Type', value: 'text/html; charset=utf-8' }] }, cookies),
    body: `<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>MGA Sprint Board</title><p style="font:16px Arial,sans-serif;margin:2rem">${html}</p>`,
  };
}

// --- flow ---

function startLogin(request, host, secrets) {
  const state = rand();
  const nonce = rand();
  const verifier = rand(32); // 43 chars, within PKCE's 43..128
  const challenge = crypto.createHash('sha256').update(verifier).digest('base64url');
  const flow = sign({ state, nonce, verifier, returnTo: safeReturnTo(request.uri, request.querystring), exp: now() + FLOW_TTL_S }, secrets.cookieKey);
  const params = new URLSearchParams({
    client_id: config.clientId,
    response_type: 'code',
    response_mode: 'query',
    redirect_uri: redirectUri(host),
    scope: SCOPE,
    state,
    nonce,
    code_challenge: challenge,
    code_challenge_method: 'S256',
  });
  return redirect(`${AUTHORITY}/oauth2/v2.0/authorize?${params}`, [cookie(FLOW_COOKIE, flow, FLOW_TTL_S)]);
}

function decodeJwtPayload(jwt) {
  const parts = String(jwt).split('.');
  if (parts.length !== 3) throw new Error('malformed id_token');
  return JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
}

function claimProblem(c, nonce) {
  if (c.iss !== ISSUER) return 'iss';
  if (c.aud !== config.clientId) return 'aud';
  if (c.tid !== config.tenantId) return 'tid';
  if (c.nonce !== nonce) return 'nonce';
  if (typeof c.exp !== 'number' || c.exp < now() - 60) return 'exp';
  if (!c.oid) return 'oid';
  return null;
}

async function redeem(code, verifier, host, secrets) {
  const res = await fetch(`${AUTHORITY}/oauth2/v2.0/token`, {
    method: 'POST',
    headers: { 'content-type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({
      client_id: config.clientId,
      client_secret: secrets.clientSecret,
      grant_type: 'authorization_code',
      code,
      redirect_uri: redirectUri(host),
      code_verifier: verifier,
      scope: SCOPE,
    }),
    signal: AbortSignal.timeout(TOKEN_TIMEOUT_MS),
  });
  const json = await res.json().catch(() => ({}));
  if (!res.ok || !json.id_token) throw new Error(`token endpoint ${res.status} ${json.error || ''}`.trim());
  return json;
}

async function callback(request, host, cookies, secrets) {
  const q = new URLSearchParams(request.querystring || '');
  const err = q.get('error');
  if (err) {
    // e.g. AADSTS50105 = user not assigned to the app. Entra's own sign-in log has the detail.
    const code = (q.get('error_description') || '').match(/AADSTS\d+/);
    console.log(JSON.stringify({ event: 'sign_in_refused', error: err.replace(/[^\w]/g, ''), code: code ? code[0] : null }));
    return page('403', 'Forbidden', `Microsoft sign-in did not let you in${code ? ` (${code[0]})` : ''}. The Sprint Board is for Insly employees; ask IT if you think you should have access.`, [clearCookie(FLOW_COOKIE)]);
  }

  const flow = verify(cookies[FLOW_COOKIE], secrets.cookieKey);
  if (!flow) {
    // No flow cookie: cookies blocked or the 10-minute window passed. Do not loop.
    return page('400', 'Bad Request', 'Sign-in could not finish. Allow cookies for this site, then <a href="/">open the Sprint Board again</a>.', [clearCookie(FLOW_COOKIE)]);
  }
  if (!q.get('code') || q.get('state') !== flow.state) {
    // Usually two tabs signing in at once: start over (the other tab may already hold a session).
    return redirect('/', [clearCookie(FLOW_COOKIE)]);
  }

  const tokens = await redeem(q.get('code'), flow.verifier, host, secrets);
  const claims = decodeJwtPayload(tokens.id_token);
  const problem = claimProblem(claims, flow.nonce);
  if (problem) {
    console.log(JSON.stringify({ event: 'sign_in_rejected', check: problem }));
    return page('403', 'Forbidden', 'Sign-in was rejected. <a href="/">Try again</a>.', [clearCookie(FLOW_COOKIE)]);
  }

  // Pseudonymous: object ID only. Names and e-mails stay in Entra's sign-in log.
  console.log(JSON.stringify({ event: 'sign_in', oid: claims.oid }));
  const session = sign({ oid: claims.oid, exp: now() + SESSION_TTL_S }, secrets.cookieKey);
  return redirect(flow.returnTo || '/', [cookie(SESSION_COOKIE, session, SESSION_TTL_S), clearCookie(FLOW_COOKIE)]);
}

async function handle(request) {
  if (request.uri === HEALTH_PATH) {
    await getSecrets(); // proves the function runs and can read its secrets; serves no content
    return page('200', 'OK', 'ok');
  }

  const secrets = await getSecrets();
  const cookies = parseCookies(request);
  const host = header(request, 'host');

  if (request.uri === CALLBACK_PATH) return callback(request, host, cookies, secrets);
  if (request.uri === LOGOUT_PATH) {
    return page('200', 'OK', 'You are signed out of the Sprint Board. <a href="/">Sign in again</a>.', [clearCookie(SESSION_COOKIE)]);
  }

  if (verify(cookies[SESSION_COOKIE], secrets.cookieKey)) return request; // pass through to S3

  if (!isNavigation(request)) return page('401', 'Unauthorized', 'Your session ended. Reload the page.');
  return startLogin(request, host, secrets);
}

exports.handler = async (event) => {
  const request = event.Records[0].cf.request;
  try {
    return await handle(request);
  } catch (e) {
    // Fail closed: no content without a verified session.
    console.error(JSON.stringify({ event: 'auth_error', message: String((e && e.message) || e) }));
    return page('503', 'Service Unavailable', 'Sign-in is unavailable right now. Try again in a minute.');
  }
};

